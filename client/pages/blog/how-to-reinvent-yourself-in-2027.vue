              <div class="brand-step-card">
                <div class="step-card-header">
                  <span class="step-badge">Step 5</span>
                  <h3 class="step-title">Pattern: Reflect and Retell Your Story</h3>
                </div>
                <div class="step-card-body">
                  <p>
                    Every two weeks, spend 20 minutes asking: <em>What did I actually do? What changed? What surprised me? What is the next experiment?</em>
                  </p>
                  <p>
                    Then deliberately update the story you tell yourself. Not <em>"I'm trying to be someone who writes"</em>, but <strong>"I write three mornings a week"</strong>.
                  </p>
                  <p class="text-sm text-muted-contrast m-0">
                    Identity follows evidence. Ibarra’s research highlights this sense-making step: arranging what you have learned into a coherent narrative of who you are becoming.
                  </p>
                </div>
