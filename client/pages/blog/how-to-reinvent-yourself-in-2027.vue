                    <div class="p-3.5 rounded-xl border border-[#D9AA55]/30 bg-[#171B48]/30">
                      <span class="text-xs font-bold uppercase tracking-wider text-[#F8D78B] block mb-1">Confidence</span>
                      <p class="text-xs text-primary-contrast m-0">Commit to speaking up once in every team meeting for two weeks straight.</p>
