              <div class="brand-step-card">
                <div class="step-card-header">
                  <span class="step-badge">Step 3</span>
                  <h3 class="step-title">Prove: Run Small Experiments</h3>
                </div>
                <div class="step-card-body">
                  <p>
                    This is where most reinventions skip a step and collapse. Following Ibarra’s research, treat each possible self as an experiment to test, not a lifetime contract to commit to.
