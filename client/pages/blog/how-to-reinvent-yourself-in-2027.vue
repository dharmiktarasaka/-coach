                  </p>
                  <p class="text-sm text-muted-contrast m-0">
                    For each one, write down what that person does on an <strong>ordinary Tuesday</strong>. Daily micro-actions are infinitely easier to test and measure than vague, distant fantasies.
                  </p>
                </div>
              </div>

