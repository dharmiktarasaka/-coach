          <!-- Can you really change yourself completely? -->
          <div class="section-block">
            <h2 class="text-2xl sm:text-3xl font-serif font-bold brand-gold-heading mb-4">
              Can You Really Change Yourself <em>Completely?</em>
            </h2>
            <p>
              You can change far more than you probably think, though not overnight.
            </p>
            <p>
              Psychologists Jordi Quoidbach, Daniel Gilbert and Timothy Wilson surveyed more than 19,000 people aged 18 to 68. They found that people of every age underestimate how much they will change in the future. They named this the <strong>"end of history illusion"</strong> (<a href="https://midus.wisc.edu/wp-content/uploads/2024/04/1256.pdf" target="_blank" rel="noopener noreferrer" class="link-inline">Science, 2013</a>). At 25, 45 or 65, we tend to assume the person we are now is roughly who we’ll always be. We’re usually wrong.
            </p>
            <p>
              There’s also evidence that people can change on purpose. In two 16-week experiments, people who wanted to change their personality traits tended to change in the direction they wanted (<a href="https://pubmed.ncbi.nlm.nih.gov/25822032/" target="_blank" rel="noopener noreferrer" class="link-inline">Hudson &amp; Fraley, 2015</a>).
            </p>
            <p>
              But the follow-up research adds the crucial condition: <strong>Wanting to change isn’t enough. Doing is what counts.</strong> The more trait-consistent challenges people actually completed, the more they changed. Those who committed and didn’t follow through moved the wrong way (<a href="https://bps.org.uk/research-digest/merely-desiring-alter-your-personality-not-enough-and-may-backfire-unless-you-take" target="_blank" rel="noopener noreferrer" class="link-inline">BPS Research Digest</a>).
            </p>
            <p class="brand-caveat">
              <em>Honest caveat:</em> These studies used students and self-reported personality. They show a pattern, not a guarantee. But the lesson is immensely practical: <strong>promise less, complete more.</strong>
            </p>
