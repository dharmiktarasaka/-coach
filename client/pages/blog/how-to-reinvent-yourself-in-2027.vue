                <div class="step-card-header">
                  <span class="step-badge">Step 4</span>
                  <h3 class="step-title">Practise: Turn What Works into Habits</h3>
                </div>
                <div class="step-card-body">
                  <p>
                    Once an experiment feels right, anchor it as a permanent habit using an <strong>if-then implementation plan</strong>: <em>"If it’s 7 am and I’ve made tea, then I will write for 15 minutes."</em>
                  </p>
                  <p>
                    A meta-analysis of 94 studies with over 8,000 participants confirmed that implementation intentions have a medium-to-large effect on reaching goals (<a href="https://www.socmot.uni-konstanz.de/sites/default/files/Gollwitzer_Oettingen_11_Planning_Goal_Striving.pdf" target="_blank" rel="noopener noreferrer" class="link-inline">Gollwitzer &amp; Oettingen</a>).
                  </p>
                  <div class="space-y-2 mt-3 text-sm text-primary-contrast">
                    <p><strong>Two golden rules make habits stick:</strong></p>
                    <p>• <strong>Phrase goals as things to start, not stop:</strong> In a study of over 1,000 resolutions, "approach" goals succeeded <strong>58.9%</strong> of the time vs <strong>47.1%</strong> for "avoidance" goals (<a href="https://pmc.ncbi.nlm.nih.gov/articles/PMC7725288" target="_blank" rel="noopener noreferrer" class="link-inline">Oscarsson et al., PLOS ONE, 2020</a>). <em>"I will eat fruit after lunch"</em> beats <em>"I will stop eating sweets"</em>.</p>
                    <p>• <strong>Start smaller than feels impressive:</strong> Remember the backfire effect. A commitment you can comfortably keep beats a heroic one you abandon by day eleven.</p>
                  </div>
                </div>
              </div>

