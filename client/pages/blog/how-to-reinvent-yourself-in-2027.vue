                      <span class="text-[#D9AA55] font-bold">&bull;</span>
                      <span>What story do I keep telling about myself that may no longer be true?</span>
                    </li>
                    <li class="flex items-start gap-2">
                      <span class="text-[#D9AA55] font-bold">&bull;</span>
                      <span>If nothing changes, where will I be in three years? How do I genuinely feel about that?</span>
                    </li>
